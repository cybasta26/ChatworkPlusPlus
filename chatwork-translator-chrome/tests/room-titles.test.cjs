const {JSDOM}=require('jsdom');
const fs=require('fs');
const assert=require('node:assert/strict');
const test=require('node:test');
const path=require('path');
for(const browser of ['chrome','edge']) test(browser+' group titles and toggle lifecycle', async()=>{
 const dom=new JSDOM(`<div class="chatRoomHeader__titleContainer"><img src="/icon/group.png"><div id="_roomTitle"><span class="chatRoomHeader__roomTitle">サーバー</span></div></div><li role="tab" data-rid="1" aria-label="サーバー"><img src="/icon/group.png"><div><p>サーバー</p></div></li><li role="tab" data-rid="2" aria-label="田中"><img src="/avatar/a.png"><div><p>田中</p></div></li>`,{runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window; let change;
 w.chrome={storage:{local:{get:async()=>({})},onChanged:{addListener:fn=>change=fn}}};
 let enabled=true; const calls=[];
 w.HTMLElement.prototype.getBoundingClientRect=()=>({width:100,top:20,bottom:40});
 w.ChatworkAutoTranslation={isEnabled:()=>enabled,translate:async text=>{calls.push(text);return {text:text==='サーバー'?'服务器':'新群'};}};
 w.eval(fs.readFileSync(path.join(__dirname,'../../chatwork-translator-'+browser+'/room-titles.js'),'utf8'));
 const wait=()=>new Promise(r=>setTimeout(r,500));
 await wait();
 assert.equal(w.document.querySelectorAll('.cw-room-translation').length,2);
 assert.deepEqual(calls,['サーバー']);
 assert.equal(w.document.querySelector('#_roomTitle').textContent,'サーバー');
 assert.equal(w.document.querySelector('[data-rid="2"] .cw-room-translation'),null);
 const p=w.document.querySelector('[data-rid="1"] p');p.textContent='新しい';p.closest('li').setAttribute('aria-label','新しい');
 await wait();assert.equal(p.nextSibling.textContent,'新群');
 enabled=false;w.document.dispatchEvent(new w.Event('cw-auto-translation-state'));await wait();
 assert.equal(w.document.querySelectorAll('.cw-room-translation,.cw-room-two-lines').length,0);
 enabled=true;w.document.dispatchEvent(new w.Event('cw-auto-translation-state'));await wait();
 assert.equal(w.document.querySelectorAll('.cw-room-translation').length,2);
 change({roomTitleTranslationEnabled:{newValue:false}},'local');await wait();
 assert.equal(w.document.querySelectorAll('.cw-room-translation').length,0);
 change({roomTitleTranslationEnabled:{newValue:true}},'local');await wait();
 assert.equal(w.document.querySelectorAll('.cw-room-translation').length,2);
 dom.window.close();
});
